from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = []


def group(prefix, title, source, rows, cleanup="刪除本案測試紀錄，還原設定並重新核對資料位置。"):
    cases = []
    for index, raw in enumerate(rows.strip().splitlines(), 1):
        parts = [part.strip() for part in raw.split("|")]
        if len(parts) != 5:
            raise ValueError(f"{prefix}-{index:03d}: expected 5 fields: {raw}")
        name, setup, steps, expected, evidence = parts
        cases.append(dict(id=f"{prefix}-{index:03d}", name=name, setup=setup,
                          steps=steps.split("；"), expected=expected, evidence=evidence))
    GROUPS.append(dict(prefix=prefix, title=title, source=source, cases=cases, cleanup=cleanup))


